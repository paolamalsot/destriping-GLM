"""Re-run the destriping portion of fit_glum.py for runs that produced Inf / NaN
in ``n_counts_adjusted``.

For each affected run directory:
    1. Move ``destriped_data/`` to ``destriped_data_with_inf/`` (backup).
    2. Re-load ``sol``, ``dist``, ``dist_params``, and the spatialAdata input
       specified in ``.hydra/config.yaml``.
    3. Call ``get_all_destripe_calls`` and re-save the outputs to
       ``destriped_data/<method>/df.parquet``.
    4. Verify that the re-computed ``n_counts_adjusted`` contains no Inf / NaN.
    5. Drop a README in the run dir describing the fix.

Designed to be launched on Euler via sbatch (see sibling ``.sh`` wrapper).
"""

from __future__ import annotations

import argparse
import gc
import logging
import pickle
import shutil
import time
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from src.spatialAdata.loading import load_spatialAdata
from src.destriping.sol import Sol
from experiments.src.custom_destriping_benchmark.utils import get_all_destripe_calls
from experiments.src.custom_destriping_benchmark.lightweight_funs import (
    save_n_counts_adjusted_counts,
)

SCRIPT_NAME = Path(__file__).name

DEFAULT_ANALYSIS_CSVS = [
    "results/segmentation_sensitivity_analysis/simulation_4_with_struct_nb_weibul_2_seed_546/analysis_merge_v6/destriped_summary_df.csv",
    "results/segmentation_sensitivity_analysis/human_lymph_node/analysis_merge_v6/destriped_summary_df.csv",
    "results/segmentation_sensitivity_analysis/human_lymph_node/analysis_split_v6/destriped_summary_df.csv",
    "results/segmentation_sensitivity_analysis/human_lymph_node/analysis_subsample_v6/destriped_summary_df.csv",
]

INF_COL = "nan_inf_destriped_data__n_counts_adjusted=True"

README_TEMPLATE = """# destriped_data re-computed on {date}

The files under `destriped_data/` were regenerated by `{script}` after a bug
produced `inf` values in `n_counts_adjusted`
(see `notebooks/debugging/debug_inf_in_destriped_data.ipynb`).

The previous buggy output is preserved under `destriped_data_with_inf/`.
"""


def collect_run_dirs(csv_paths: list[str]) -> list[str]:
    """Return deduplicated list of run_dir strings that have Inf / NaN flagged."""
    seen: set[str] = set()
    for csv_path in csv_paths:
        df = pd.read_csv(csv_path)
        sub = df.loc[df[INF_COL] == True]
        seen.update(sub["run_dir"].unique().tolist())
    return sorted(seen)


def _backup_destriped_data(run_dir: Path, logger: logging.Logger) -> None:
    src = run_dir / "destriped_data"
    dst = run_dir / "destriped_data_with_inf"
    if src.exists() and not dst.exists():
        shutil.move(str(src), str(dst))
        logger.info("moved %s -> %s", src, dst)
    elif not src.exists() and dst.exists():
        logger.info("backup already exists at %s; proceeding with recompute", dst)
    elif src.exists() and dst.exists():
        raise RuntimeError(
            f"Both {src} and {dst} exist; refusing to overwrite. Inspect manually."
        )
    else:
        raise RuntimeError(f"Neither {src} nor {dst} exists.")


def fix_run(
    run_dir: str,
    data_cache: dict[str, object],
    logger: logging.Logger,
) -> None:
    run_dir = Path(run_dir)
    logger.info("== fixing %s", run_dir)
    _backup_destriped_data(run_dir, logger)

    cfg = yaml.safe_load((run_dir / ".hydra/config.yaml").read_text())
    data_path = cfg["dataset"]["path_data"]
    cell_id_label = cfg["dataset"]["cell_id_label"]

    if data_path not in data_cache:
        logger.info("loading spatialAdata from %s", data_path)
        data_cache[data_path] = load_spatialAdata(data_path)
    data = data_cache[data_path]

    sol = Sol.load(run_dir / "sol")
    with open(run_dir / "dist.pkl", "rb") as fh:
        d = pickle.load(fh)
    dist, dist_params = d["dist"], d["dist_params"]

    destriping_calls = get_all_destripe_calls(
        sol,
        None,  # model not actually used
        data,
        cell_id_label=cell_id_label,
        dist=dist,
        dist_params=dist_params,
    )

    for name, call in destriping_calls.items():
        logger.info("  %s", name)
        t0 = time.time()
        destriped = call()
        dt = time.time() - t0
        out_dir = run_dir / "destriped_data" / name
        save_n_counts_adjusted_counts(destriped, str(out_dir))

        df = pd.read_parquet(out_dir / "df.parquet")
        vals = df["n_counts_adjusted"]
        n_nan = int(vals.isna().sum())
        n_inf = int(np.isinf(vals).sum())
        logger.info("    saved in %.1fs | n_nan=%d n_inf=%d", dt, n_nan, n_inf)
        if n_nan > 0 or n_inf > 0:
            raise RuntimeError(
                f"Re-computed output at {out_dir} still contains NaN/Inf "
                f"(nan={n_nan}, inf={n_inf})."
            )
        del destriped
        gc.collect()

    readme = run_dir / "DESTRIPED_DATA_FIX_README.md"
    readme.write_text(
        README_TEMPLATE.format(
            date=datetime.now().strftime("%Y-%m-%d"), script=SCRIPT_NAME
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--csv",
        action="append",
        help="Path to a destriped_summary_df.csv. Can be passed multiple times. "
             "Defaults to DEFAULT_ANALYSIS_CSVS when omitted.",
    )
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(message)s",
    )
    logger = logging.getLogger("fix_inf")

    csv_paths = args.csv if args.csv else DEFAULT_ANALYSIS_CSVS
    run_dirs = collect_run_dirs(csv_paths)
    logger.info("found %d unique runs to fix", len(run_dirs))
    for rd in run_dirs:
        logger.info("  - %s", rd)

    data_cache: dict[str, object] = {}
    failed: list[tuple[str, str]] = []
    for rd in run_dirs:
        try:
            fix_run(rd, data_cache, logger)
        except Exception as exc:  # noqa: BLE001
            logger.exception("FAILED for %s", rd)
            failed.append((rd, repr(exc)))

    logger.info("done: %d / %d successful", len(run_dirs) - len(failed), len(run_dirs))
    if failed:
        for rd, err in failed:
            logger.error("FAILED %s: %s", rd, err)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
